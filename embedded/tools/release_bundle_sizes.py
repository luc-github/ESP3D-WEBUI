#!/usr/bin/env python3
"""
ESP3D embedded page release bundle sizes report.

1. Runs `npm run buildall` (builds every target: esp3d, esp3dlib, grblhal...).
2. Scans dist/<target>/ for index.html.gz and index.html.br and collects sizes.
3. Writes a Markdown document with a table: target, gzip path/size,
   brotli path/size.

Same report as tools/release_bundle_sizes.py of ESP3D-WEBUI, for the
embedded page layout (one level: dist/<target>/).

Usage:
  python tools/release_bundle_sizes.py
  python tools/release_bundle_sizes.py --no-build
  python tools/release_bundle_sizes.py --output docs/BUNDLE_SIZES.md

Copyright (c) 2025 Luc Lebosse. All rights reserved.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path


def human_size(size_bytes: int) -> str:
    if size_bytes < 1024:
        return f"{size_bytes} B"
    if size_bytes < 1024 * 1024:
        return f"{size_bytes / 1024:.1f} KB"
    return f"{size_bytes / (1024 * 1024):.2f} MB"


def collect_sizes(dist_root: Path) -> dict[str, dict[str, tuple[int, str]]]:
    """Returns {target: {"gz"|"br": (size_bytes, rel_path)}}."""
    packages: dict[str, dict[str, tuple[int, str]]] = {}
    if not dist_root.is_dir():
        return packages
    for target_dir in sorted(dist_root.iterdir()):
        if not target_dir.is_dir():
            continue
        found: dict[str, tuple[int, str]] = {}
        for kind in ("gz", "br"):
            f = target_dir / f"index.html.{kind}"
            if f.is_file():
                found[kind] = (f.stat().st_size, f.relative_to(dist_root).as_posix())
        if found:
            packages[target_dir.name] = found
    return packages


def main() -> int:
    parser = argparse.ArgumentParser(description="Build all targets and report bundle sizes.")
    parser.add_argument(
        "--no-build",
        action="store_true",
        help="Skip npm run buildall; only scan existing dist/.",
    )
    parser.add_argument(
        "--output",
        "-o",
        default=None,
        help="Output Markdown file path (default: dist/BUNDLE_SIZES.md).",
    )
    parser.add_argument(
        "--root",
        default=None,
        help="Embedded page root (default: parent of tools/).",
    )
    args = parser.parse_args()

    root = Path(args.root) if args.root else Path(__file__).resolve().parent.parent
    dist_root = root / "dist"
    output_path = Path(args.output) if args.output else dist_root / "BUNDLE_SIZES.md"

    if not args.no_build:
        print("Running: npm run buildall")
        r = subprocess.run(
            ["npm", "run", "buildall"],
            cwd=root,
            shell=sys.platform == "win32",
        )
        if r.returncode != 0:
            print("Build failed.", file=sys.stderr)
            return r.returncode

    packages = collect_sizes(dist_root)
    if not packages:
        print("No index.html.gz/.br found under dist/<target>/. Run without --no-build first.", file=sys.stderr)
        return 1

    lines = [
        "# Embedded page bundle sizes (dist/)",
        "",
        "Generated by `tools/release_bundle_sizes.py`.",
        "",
        "| Target | Gzip Path | Gzip Size | Gzip Bytes | Brotli Path | Brotli Size | Brotli Bytes |",
        "|--------|-----------|-----------|------------|-------------|-------------|--------------|",
    ]

    total_gz = 0
    total_br = 0
    for target, found in sorted(packages.items()):
        gz_size, gz_path = found.get("gz", (0, "N/A"))
        br_size, br_path = found.get("br", (0, "N/A"))
        total_gz += gz_size
        total_br += br_size
        lines.append(
            f"| {target} | {gz_path} | {human_size(gz_size) if gz_size else 'N/A'} | {gz_size or 'N/A'} "
            f"| {br_path} | {human_size(br_size) if br_size else 'N/A'} | {br_size or 'N/A'} |"
        )

    lines.extend([
        "",
        f"**Total Gzip size:** {human_size(total_gz)} ({total_gz} bytes).",
        f"**Total Brotli size:** {human_size(total_br)} ({total_br} bytes).",
        "",
    ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
